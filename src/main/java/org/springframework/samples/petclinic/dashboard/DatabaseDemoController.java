package org.springframework.samples.petclinic.dashboard;

import java.util.List;
import java.util.function.Supplier;
import java.util.stream.Collectors;

import org.springframework.data.domain.PageRequest;
import org.springframework.http.ResponseEntity;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.samples.petclinic.dashboard.SqlRecorder.Recorded;
import org.springframework.samples.petclinic.owner.Owner;
import org.springframework.samples.petclinic.owner.OwnerRepository;
import org.springframework.samples.petclinic.owner.Pet;
import org.springframework.samples.petclinic.owner.PetType;
import org.springframework.samples.petclinic.owner.PetTypeRepository;
import org.springframework.transaction.support.TransactionTemplate;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;

/**
 * Shows how objects reach the database: row counts and the SQL generated by Hibernate for
 * a few repository calls.
 */
@RestController
class DatabaseDemoController {

	private static final List<String> TABLES = List.of("owners", "pets", "types", "visits", "vets", "specialties",
			"vet_specialties");

	private final JdbcTemplate jdbc;

	private final OwnerRepository owners;

	private final PetTypeRepository petTypes;

	private final TransactionTemplate transactions;

	private final SqlRecorder sqlRecorder;

	DatabaseDemoController(JdbcTemplate jdbc, OwnerRepository owners, PetTypeRepository petTypes,
			TransactionTemplate transactions, SqlRecorder sqlRecorder) {
		this.jdbc = jdbc;
		this.owners = owners;
		this.petTypes = petTypes;
		this.transactions = transactions;
		this.sqlRecorder = sqlRecorder;
	}

	record TableCount(String table, long rows) {
	}

	record QueryDemo(String demo, List<String> sql, long millis, int objects, List<String> result) {
	}

	@GetMapping("/api/dashboard/database")
	List<TableCount> tableCounts() {
		return TABLES.stream()
			.map(table -> new TableCount(table, this.jdbc.queryForObject("SELECT COUNT(*) FROM " + table, Long.class)))
			.toList();
	}

	@GetMapping("/api/dashboard/sql")
	ResponseEntity<QueryDemo> sql(@RequestParam String demo) {
		return switch (demo) {
			case "findById" -> ResponseEntity.ok(run(demo, () -> this.owners.findById(1).stream().toList()));
			case "findByLastName" -> ResponseEntity.ok(run(demo,
					() -> this.owners.findByLastNameStartingWith("Davis", PageRequest.of(0, 5)).getContent()));
			case "query" -> ResponseEntity.ok(run(demo, this.petTypes::findPetTypes));
			case "rollback" -> ResponseEntity.ok(run(demo, this::insertAndRollBack));
			default -> ResponseEntity.badRequest().build();
		};
	}

	private List<?> insertAndRollBack() {
		return this.transactions.execute(status -> {
			PetType type = new PetType();
			type.setName("demo-rollback");
			PetType saved = this.petTypes.saveAndFlush(type);
			status.setRollbackOnly();
			return List.of(saved);
		});
	}

	private QueryDemo run(String demo, Supplier<List<?>> action) {
		Recorded<List<?>> recorded = this.sqlRecorder.record(action);
		List<String> result = recorded.result().stream().map(DatabaseDemoController::describe).toList();
		return new QueryDemo(demo, recorded.statements(), recorded.millis(), result.size(), result);
	}

	private static String describe(Object entity) {
		if (entity instanceof Owner owner) {
			String pets = owner.getPets()
				.stream()
				.map(DatabaseDemoController::describePet)
				.collect(Collectors.joining(", ", "[", "]"));
			return "Owner{id=" + owner.getId() + ", " + owner.getFirstName() + " " + owner.getLastName() + ", pets="
					+ pets + "}";
		}
		if (entity instanceof PetType type) {
			return "PetType{id=" + type.getId() + ", name=" + type.getName() + "}";
		}
		return String.valueOf(entity);
	}

	private static String describePet(Pet pet) {
		return "Pet{" + pet.getName() + ", " + pet.getType() + ", visits=" + pet.getVisits().size() + "}";
	}

}
